def _cmp_word(a, b, tol=0.005):
    return "lower" if a < b - tol else ("higher" if a > b + tol else "similar")


def _sig(p, alpha=0.05):
    return "significant" if p < alpha else "not significant"


def _p(p):
    return "< 0.0001" if p < 1e-4 else (f"= {p:.4f}" if p < 0.01 else f"= {p:.3f}")


