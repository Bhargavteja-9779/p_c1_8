def _fx(v):
    """Format a multiplicative factor; very large factors in powers of ten (pandoc superscript)."""
    if not np.isfinite(v):
        return "–"
    if v >= 1000:
        e = int(np.floor(np.log10(v)))
        return f"{v / 10 ** e:.1f} × 10^{e}^"
    return f"{v:.2f}"


